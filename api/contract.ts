import type { APIResponse } from '@playwright/test';
import { Ajv2020, type ValidateFunction } from 'ajv/dist/2020';
import addFormats from 'ajv-formats';

type HttpMethod = 'get' | 'post' | 'put' | 'delete';
type JsonSchema = Record<string, unknown>;

interface OpenApiResponse {
  content?: Record<string, { schema?: JsonSchema }>;
}

export interface OpenApiDocument {
  paths: Record<string, Partial<Record<HttpMethod, { responses?: Record<string, OpenApiResponse> }>>>;
  components?: { schemas?: Record<string, JsonSchema> };
}

/** An endpoint as the OpenAPI document names it: method and path template. */
export interface Operation {
  method: HttpMethod;
  path: string;
}

/** A response that doesn't match the API's OpenAPI contract. */
export class ContractError extends Error {
  override name = 'ContractError';
}

/**
 * Validates responses against one OpenAPI document.
 *
 * eShop's documents are generated by ASP.NET and are looser than what the API really returns, so
 * two rules tighten them before validating:
 * - a property whose schema doesn't allow null is required (ASP.NET marks almost nothing required,
 *   yet always serializes every property);
 * - a number typed as "number or numeric string" must be a number (ASP.NET documents that it
 *   accepts strings on input; responses always send numbers).
 */
export class ContractValidator {
  private readonly ajv = new Ajv2020({ allErrors: true, strict: false });
  private readonly document: OpenApiDocument;
  private readonly compiled = new Map<string, ValidateFunction>();

  constructor(
    private readonly name: string,
    document: OpenApiDocument,
  ) {
    addFormats(this.ajv);
    this.ajv.addFormat('int32', { type: 'number', validate: isInt32 });
    this.ajv.addFormat('int64', { type: 'number', validate: Number.isSafeInteger });
    this.ajv.addFormat('double', { type: 'number', validate: Number.isFinite });
    this.ajv.addFormat('float', { type: 'number', validate: Number.isFinite });

    this.document = tighten(withAbsoluteRefs(document, name)) as OpenApiDocument;
    this.ajv.addSchema({ $id: name, components: this.document.components ?? {} });
  }

  /** Throws a `ContractError` if the response's status, content type or body breaks the contract. */
  async validate(response: APIResponse, operation: Operation): Promise<void> {
    this.check(operation, response.status(), response.headers()['content-type'], await response.text());
  }

  /** Same as `validate`, for a response already read into its parts. */
  check(operation: Operation, status: number, contentType: string | undefined, body: string): void {
    const where = `${operation.method.toUpperCase()} ${operation.path} -> ${status} (${this.name})`;
    const responses = this.document.paths[operation.path]?.[operation.method]?.responses;
    if (!responses) throw new ContractError(`${where}: the contract has no such operation`);

    const documented = responses[String(status)];
    if (!documented) {
      throw new ContractError(`${where}: status is not in the contract (documented: ${Object.keys(responses).join(', ')})`);
    }

    const content = documented.content ?? {};
    if (Object.keys(content).length === 0) {
      if (body.trim() !== '') {
        throw new ContractError(`${where}: returned a body (${contentType ?? 'no content type'}), but the contract documents none`);
      }
      return;
    }

    const mediaType = (contentType ?? '').split(';')[0]!.trim().toLowerCase();
    const schema = content[mediaType]?.schema;
    if (!content[mediaType]) {
      throw new ContractError(`${where}: content type "${mediaType}" is not in the contract (documented: ${Object.keys(content).join(', ')})`);
    }
    if (!schema) return;

    let parsed: unknown;
    try {
      parsed = JSON.parse(body);
    } catch {
      throw new ContractError(`${where}: body is not valid JSON`);
    }

    const validate = this.compile(`${operation.method} ${operation.path} ${status} ${mediaType}`, schema);
    if (!validate(parsed)) {
      const problems = (validate.errors ?? [])
        .map(error => `${error.instancePath || '(body)'} ${error.message ?? 'is invalid'}`)
        .join('; ');
      throw new ContractError(`${where}: ${problems}`);
    }
  }

  private compile(key: string, schema: JsonSchema): ValidateFunction {
    let validate = this.compiled.get(key);
    if (!validate) {
      validate = this.ajv.compile(schema);
      this.compiled.set(key, validate);
    }
    return validate;
  }
}

function isInt32(value: number): boolean {
  return Number.isInteger(value) && value >= -(2 ** 31) && value < 2 ** 31;
}

/** Rewrites local `#/...` references to `<name>#/...` so schemas compiled on their own still resolve. */
function withAbsoluteRefs(document: OpenApiDocument, name: string): unknown {
  return JSON.parse(JSON.stringify(document).replaceAll('"$ref":"#/', `"$ref":"${name}#/`));
}

function isNullable(schema: unknown): boolean {
  if (!schema || typeof schema !== 'object') return false;
  const { type, oneOf, anyOf } = schema as { type?: unknown; oneOf?: unknown[]; anyOf?: unknown[] };
  if (type === 'null' || (Array.isArray(type) && type.includes('null'))) return true;
  return [...(oneOf ?? []), ...(anyOf ?? [])].some(isNullable);
}

/** Applies the two tightening rules described on `ContractValidator`, recursively. */
function tighten(node: unknown): unknown {
  if (Array.isArray(node)) return node.map(tighten);
  if (!node || typeof node !== 'object') return node;

  const result: Record<string, unknown> = {};
  for (const [key, value] of Object.entries(node)) result[key] = tighten(value);

  const type = result.type;
  if (Array.isArray(type) && type.includes('string') && (type.includes('integer') || type.includes('number'))) {
    result.type = type.filter(t => t !== 'string');
    delete result.pattern;
  }

  const properties = result.properties;
  if (properties && typeof properties === 'object' && !Array.isArray(properties)) {
    const required = new Set(Array.isArray(result.required) ? (result.required as string[]) : []);
    for (const [property, schema] of Object.entries(properties)) {
      if (!isNullable(schema)) required.add(property);
    }
    result.required = [...required];
  }
  return result;
}
